def hint_for_hole(text: str) -> str:
    lower = text.lower()
    if "gps" in lower or "маршрут" in lower or "взл" in lower:
        return "Проверьте, есть ли в .BIN сообщения GPS со статусом 3D. Нет сообщений — маршрут остаётся пустым. Курс и барометр маршрут не заменяют."
    if "парол" in lower or "auth" in lower:
        return "Введите пароль страницы приёмника сами. Повторный перебор не запускается."
    if "протокол" in lower:
        return "Протокол берётся из строки прошивки модуля. Надпись на плате даёт только поле «плата»."
    if "vtx" in lower or "видео" in lower or "канал" in lower:
        return "Модель видеопередатчика впишите с шильдика. Канал появится после dump all или таблицы VX приёмника."
    if "приём" in lower or "rx" in lower:
        return "Сначала страница 10.0.0.1. Потом проход через полётник. Пайка к TX/RX — только если оба пути молчат."
    return "Оставьте поле пустым и сохраните причину. Не подставляйте типичное значение."
